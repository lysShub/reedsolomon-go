func mulGo(a, b byte) byte {
	return mulTable()[a][b]
}

func mulVectGo(c byte, in, out []byte) {
	switch c {
	case 0:
		clear(out[:len(in)])
	case 1:
		copy(out[:len(in)], in)
	default:
		t := mulTable()[c]
		for i := range in {
			out[i] = t[in[i]]
		}
	}
}

func mulXorVectGo(c byte, in, out []byte) {
	switch c {
	case 0:
		_ = out[:len(in)]
	case 1:
		xorVect(in, out)
	default:
		t := mulTable()[c]
		for i := range in {
			out[i] ^= t[in[i]]
		}
	}
}

func xorVectGo(in, out []byte) {
	if debug.Debug() {
		debug.GreaterOrEqual(len(out), len(in))
	}

	wi, wo := to(in), to(out)
	for i := 0; i < len(wi); i += 4 {
		wo[i+0] = wi[i+0] ^ wo[i+0]
		wo[i+1] = wi[i+1] ^ wo[i+1]
		wo[i+2] = wi[i+2] ^ wo[i+2]
		wo[i+3] = wi[i+3] ^ wo[i+3]
	}

	i := len(wi) * 8
	for ; i < len(in); i++ {
		out[i] = in[i] ^ out[i]
	}
}

func to(s []byte) []uint64 {
	ptr := (*uint64)(unsafe.Pointer(unsafe.SliceData(s)))
	n := (len(s) / 32) * 4
	return unsafe.Slice(ptr, n)
}

func lastIndexGo(s []byte, v byte) int {
	return bytes.LastIndexByte(s, v)
}

