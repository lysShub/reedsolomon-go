type lohi struct {
	lo [16]byte // low table
	hi [16]byte // high table
}

var _ = ([1]byte{})[unsafe.Sizeof(lohi{})-16*2]

func mulTable() *[256][256]byte {
	if ptr := _mulTable.Load(); ptr != nil {
		return ptr
	}
	mul := _newMul()

	_mulTable.Store(mul)
	return mul
}
func _newMul() *[256][256]byte {
	var mul [256][256]byte
	for a := range mul {
		for b := range mul[a] {
			if a == 0 || b == 0 {
				mul[a][b] = 0
				continue
			}
			logA := int(logTable[a])
			logB := int(logTable[b])
			logSum := logA + logB
			for logSum >= 255 {
				logSum -= 255
			}
			mul[a][b] = expTable[logSum]
		}
	}
	return &mul
}

func lohiTable() *[256]lohi {
	if ptr := _lohiTable.Load(); ptr != nil {
		return ptr
	}

	var t = [256]lohi{}
	mul := _newMul()
	defer func() {
		// 在支持SIMD加速的环境中, 通常不需要查mul表, 生成lohi表后, 将其回收节约内存
		runtime.GC()
	}()
	for i := 0; i < 256; i++ {
		for j := 0; j < 256; j++ {
			var v byte
			if !(i == 0 || j == 0) {
				v = mul[i][j]
			}

			if (j & 0x0f) == j {
				t[i].lo[j] = v
			}
			if (j & 0xf0) == j {
				t[i].hi[j>>4] = v
			}
		}
	}

	_lohiTable.Store(&t)
	return _lohiTable.Load()
}
